#!/usr/bin/env node
const fs = require('fs');
const path = require('path');

const contractsDir = path.resolve(__dirname, '..');
const webContractsDir = path.resolve(__dirname, '../../web/src/contracts');

// 1. Locate Tiketa artifact
const artifactPath = path.join(contractsDir, 'out/Tiketa.sol/Tiketa.json');
if (!fs.existsSync(artifactPath)) {
  console.error('Artifact not found at', artifactPath);
  console.error('Please run "forge build" in the contracts directory first.');
  process.exit(1);
}

const artifact = JSON.parse(fs.readFileSync(artifactPath, 'utf8'));
const abi = artifact.abi;

// 2. Find deployed address
let deployedAddress = process.argv[2] || process.env.TIKETA_CONTRACT_ADDRESS || '';

if (!deployedAddress) {
  // Check broadcast directories for chain 968 or latest
  const broadcastDir = path.join(contractsDir, 'broadcast/Deploy.s.sol');
  if (fs.existsSync(broadcastDir)) {
    const chainDirs = fs.readdirSync(broadcastDir);
    for (const chain of ['968', ...chainDirs]) {
      const runLatest = path.join(broadcastDir, chain, 'run-latest.json');
      if (fs.existsSync(runLatest)) {
        try {
          const runData = JSON.parse(fs.readFileSync(runLatest, 'utf8'));
          const txs = runData.transactions || [];
          for (const tx of txs) {
            if (tx.contractName === 'Tiketa' && tx.contractAddress) {
              deployedAddress = tx.contractAddress;
              console.log(`Found deployed Tiketa on chain ${chain}: ${deployedAddress}`);
              break;
            }
          }
        } catch (e) {
          // ignore error reading run-latest
        }
      }
      if (deployedAddress) break;
    }
  }
}

// 3. Check if existing web/src/contracts/Tiketa.json has an address
const targetJsonPath = path.join(webContractsDir, 'Tiketa.json');
if (!deployedAddress && fs.existsSync(targetJsonPath)) {
  try {
    const existing = JSON.parse(fs.readFileSync(targetJsonPath, 'utf8'));
    if (existing.address && existing.address !== '0x0000000000000000000000000000000000000000') {
      deployedAddress = existing.address;
    }
  } catch (e) {}
}

if (!deployedAddress) {
  deployedAddress = '0x0000000000000000000000000000000000000000';
  console.log('No deployed address detected yet. Setting placeholder address.');
} else {
  console.log(`Using contract address: ${deployedAddress}`);
}

// 4. Ensure destination directory exists
if (!fs.existsSync(webContractsDir)) {
  fs.mkdirSync(webContractsDir, { recursive: true });
}

// 5. Write web/src/contracts/Tiketa.json
const outputData = {
  address: deployedAddress,
  chainId: 968,
  network: 'Botchain Testnet',
  abi: abi
};

fs.writeFileSync(targetJsonPath, JSON.stringify(outputData, null, 2));
console.log(`Wrote ABI and contract address to ${targetJsonPath}`);

// 6. Write TypeScript helper
const tsContent = `// Auto-generated by exportContracts.js
export const TIKETA_ADDRESS = "${deployedAddress}" as const;
export const BOTCHAIN_CHAIN_ID = 968;
export const BOTCHAIN_HEX_CHAIN_ID = "0x3c8";

export const BOTCHAIN_NETWORK = {
  chainId: "0x3c8", // 968 in hex
  chainName: "Botchain Testnet",
  nativeCurrency: {
    name: "BOT",
    symbol: "BOT",
    decimals: 18,
  },
  rpcUrls: ["https://rpc.bohr.life"],
  blockExplorerUrls: ["https://scan.bohr.life/"],
} as const;

export const TIKETA_ABI = ${JSON.stringify(abi, null, 2)} as const;
`;

const tsPath = path.join(webContractsDir, 'index.ts');
fs.writeFileSync(tsPath, tsContent);
console.log(`Wrote TypeScript contract exports to ${tsPath}`);
